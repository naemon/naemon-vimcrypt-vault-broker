/*
 * Tests for the vault module, run by "make check".
 *
 * Like naemon's own lib/test-nsutils.c, the code under test is included, so
 * static functions and variables are reachable. It is linked against the real
 * libnaemon, nothing is stubbed. Error messages are read back from the log
 * file written by libnaemon's nm_log().
 *
 * tests/vim/NN.cfg were encrypted by vim, password "test", plaintext length NN:
 *   vim -Nu NONE -n -es NN.cfg "+set cm=blowfish2" "+set key=test" "+wq"
 * Their plaintexts are listed in kat[] below; check them with "vim tests/vim/16.cfg".
 * All other vault files are generated by encrypt_vault(), which is first
 * proven to produce exactly the bytes vim wrote.
 */
#include "../module.c"
#include <ftw.h>

static const struct {
	const char *file, *text;
} kat[] = {
	{ "16.cfg", "$VAULT1$=012345\n" },
	{ "17.cfg", "$VAULT1$=0123456\n" },
	{ "18.cfg", "$VAULT1$=01234567\n" },
	{ "19.cfg", "$VAULT1$=012345678\n" },
	{ "20.cfg", "$VAULT1$=0123456789\n" },
	{ "21.cfg", "$VAULT1$=0123456789a\n" },
	{ "22.cfg", "$VAULT1$=0123456789ab\n" },
	{ "23.cfg", "$VAULT1$=0123456789abc\n" },
};

static int tests, failures, partial_store;
static char *fixture_password = "test";
static char workdir[] = "/tmp/test-vault.XXXXXX";
static char logpath[PATH_MAX], logged[8192];

static int ok(int success, const char *name)
{
	tests++;
	if(!success)
		failures++;
	printf("%sok %d - %s\n", success ? "" : "not ", tests, name);
	return success;
}

/* write a file below the work directory, creating its parent directories */
static void write_file(const char *rel, const char *data, size_t len)
{
	char path[PATH_MAX];
	FILE *fp;

	snprintf(path, sizeof(path), "%s/%s", workdir, rel);
	nspath_mkdir_p(path, 0700, NSPATH_MKDIR_SKIP_LAST);
	if(!(fp = fopen(path, "w")) || fwrite(data, 1, len, fp) != len || fclose(fp)) {
		printf("Bail out! cannot write %s\n", path);
		exit(1);
	}
}

/* what vim writes with cryptmethod blowfish2: the inverse of decrypt_vault() */
static void encrypt_vault(char *out, const char *salt, const char *seed, const char *text, int len)
{
	char block[8];
	BF_KEY *bfkey;

	master_password = fixture_password;
	bfkey = bfopen((char *)salt, 8);
	memcpy(out, "VimCrypt~03!", 12);
	memcpy(out + 12, salt, 8);
	memcpy(out + 20, seed, 8);
	/* cfb: each ciphertext block is the encrypted previous ciphertext block xor the plaintext */
	for(int offset = 0; offset < len; offset += 8) {
		memcpy(block, out + 20 + offset, 8);
		BF_encrypt((unsigned int *)block, bfkey);
		xor_bytes(out + 28 + offset, block, (char *)text + offset, len - offset < 8 ? len - offset : 8);
	}
}

/* write an encrypted vault file, with a different salt and seed each time */
static void write_vault(const char *rel, const char *text)
{
	static unsigned int files;
	char salt[9], seed[9], *data;
	int len = strlen(text);

	snprintf(salt, sizeof(salt), "salt%04u", files % 10000);
	snprintf(seed, sizeof(seed), "seed%04u", files++ % 10000);
	data = nm_malloc(28 + len);
	encrypt_vault(data, salt, seed, text, len);
	write_file(rel, data, 28 + len);
	free(data);
}

/* load a vault like naemon does, return "OK: name=value ..." or "ERROR: <log>" */
static const char *load(const char *root, const char *options)
{
	static char result[16384];
	char args[PATH_MAX + 256];
	nebstruct_vault_macro_data data;
	size_t len;
	FILE *fp;
	int loaded;

	if(truncate(logpath, 0) != 0 && errno != ENOENT) {
		printf("Bail out! cannot truncate %s\n", logpath);
		exit(1);
	}
	snprintf(args, sizeof(args), "vault=%s/%s password=test %s", workdir, root, options);
	max_files = 64;
	warn_no_match = FALSE;

	loaded = parse_args(args) == OK && parse_vault() == OK;
	len = 0;
	if((fp = fopen(logpath, "r"))) {
		len = fread(logged, 1, sizeof(logged) - 1, fp);
		fclose(fp);
	}
	logged[len] = '\0';

	if(loaded) {
		/* look every macro up through the callback naemon uses */
		len = snprintf(result, sizeof(result), "OK:");
		for(int i = 0; i < macro_store->kv_pairs && len < sizeof(result); i++) {
			memset(&data, 0, sizeof(data));
			data.macro_name = macro_store->kv[i].key;
			handle_vault_macro(NEBCALLBACK_VAULT_MACRO_DATA, &data);
			len += snprintf(result + len, sizeof(result) - len, " %s=%s", data.macro_name, data.value ? data.value : "(null)");
			free(data.value);
		}
	} else {
		snprintf(result, sizeof(result), "ERROR: %s", logged);
		partial_store = macro_store != NULL;
	}
	kvvec_destroy(macro_store, KVVEC_FREE_ALL);
	macro_store = NULL;
	return result;
}

/* expect either the exact "OK: ..." result or "ERROR: <part of the log message>" */
static void check(const char *name, const char *root, const char *options, const char *expected)
{
	const char *got = load(root, options);
	int success;

	if(strncmp(expected, "ERROR: ", 7) == 0)
		success = strncmp(got, "ERROR: ", 7) == 0 && strstr(got, expected + 7) != NULL;
	else
		success = strcmp(got, expected) == 0;
	if(!ok(success, name))
		printf("#   expected: %s\n#   got:      %s\n", expected, got);
}

static void test_vim_compatibility(const char *kat_dir)
{
	char path[PATH_MAX], name[128], expected[64], data[64], generated[64];
	size_t size;
	FILE *fp;

	for(size_t i = 0; i < ARRAY_SIZE(kat); i++) {
		int len = strlen(kat[i].text);

		snprintf(path, sizeof(path), "%s/%s", kat_dir, kat[i].file);
		if(!(fp = fopen(path, "r"))) {
			printf("Bail out! cannot read %s\n", path);
			exit(1);
		}
		size = fread(data, 1, sizeof(data), fp);
		fclose(fp);

		/* the generator must produce exactly what vim wrote, given vim's salt and seed */
		encrypt_vault(generated, data + 12, data + 20, kat[i].text, len);
		snprintf(name, sizeof(name), "Key derivation: generator writes the same bytes as vim for %s", kat[i].file);
		if(!ok(size == (size_t)28 + len && memcmp(data, generated, size) == 0, name)) {
			printf("Bail out! generated vault files would not be vim compatible\n");
			exit(1);
		}

		/* and the module must decrypt vim's file */
		write_file(kat[i].file, data, size);
		snprintf(name, sizeof(name), "Every partial block length: vim file %s (%d bytes) decrypts", kat[i].file, len);
		snprintf(expected, sizeof(expected), "OK: VAULT1=%.*s", len - 10, kat[i].text + 9);
		check(name, kat[i].file, "", expected);
	}
	check("wrong password", "16.cfg", "password=wrong", "ERROR: 16.cfg");
}

static void test_single_file(void)
{
	char plain[] = "$VAULT1$=this is a plaintext file and must not be accepted\n";
	char unsupported[40] = "VimCrypt~02!";

	write_vault("macros.cfg", "# comment\n\n$VAULT1$=one\n$VAULT:EXAMPLE$=not only numbers...\n$VAULT2$=a=b\n");
	check("macros, comments and blank lines", "macros.cfg", "", "OK: VAULT1=one VAULT:EXAMPLE=not only numbers... VAULT2=a=b");
	write_vault("blank.cfg", "$VAULT1$= leading blank\n");
	check("a blank after = belongs to the value", "blank.cfg", "", "OK: VAULT1= leading blank");

	write_vault("noequal.cfg", "$VAULT1$\n");
	check("parse error: no =", "noequal.cfg", "", "ERROR: parse error in vault file");
	write_vault("novalue.cfg", "$VAULT1$=\n");
	check("parse error: empty value", "novalue.cfg", "", "ERROR: parse error in vault file");
	write_vault("blankname.cfg", "$VAULT1$ =x\n");
	check("parse error: blank before =", "blankname.cfg", "", "ERROR: parse error in vault file");
	write_vault("user.cfg", "$USER1$=x\n");
	check("parse error: not a $VAULT macro", "user.cfg", "", "ERROR: parse error in vault file");

	write_file("plain.cfg", plain, strlen(plain));
	check("plaintext file", "plain.cfg", "", "ERROR: is not a vim crypted file");
	write_file("unsupported.cfg", unsupported, sizeof(unsupported));
	check("unsupported crypt method", "unsupported.cfg", "", "ERROR: uses unsupported crypt method");
	check("missing file", "missing.cfg", "", "ERROR: cannot read vault file");
}

static void test_bounds(void)
{
	char data[64], long_text[2048] = "", name[64], expected[sizeof(long_text) + 16] = "OK:";
	const char *text = "$VAULT1$=0123456789\n";
	int len = strlen(text);

	/* vim writes 12 bytes header, 8 bytes salt, 8 bytes seed, then the ciphertext */
	encrypt_vault(data, "saltsalt", "seedseed", text, len);
	for(int size = 5; size < 28; size += 5) {
		write_file("truncated.cfg", data, size);
		snprintf(name, sizeof(name), "Truncated file: after %d bytes", size);
		check(name, "truncated.cfg", "", size < 12 ? "ERROR: is not a vim crypted file" : "ERROR: is truncated");
	}
	write_file("short.cfg", "short\n", 6);
	check("plaintext file shorter than a header", "short.cfg", "", "ERROR: is not a vim crypted file");
	check("directory instead of a file", "", "", "ERROR: is not a vim crypted file");
	write_vault("empty.cfg", "");
	check("empty plaintext", "empty.cfg", "", "ERROR: no macros found");

	/* many blocks, values of all lengths */
	for(int i = 0; i < 40; i++) {
		snprintf(long_text + strlen(long_text), sizeof(long_text) - strlen(long_text), "$VAULT%d$=%.*s\n", i, i + 1, "abcdefghijklmnopqrstuvwxyz0123456789ABCDEFGH");
		snprintf(expected + strlen(expected), sizeof(expected) - strlen(expected), " VAULT%d=%.*s", i, i + 1, "abcdefghijklmnopqrstuvwxyz0123456789ABCDEFGH");
	}
	write_vault("long.cfg", long_text);
	check("vault with many blocks", "long.cfg", "", expected);
}

/* scenarios of the vault-includes spec, named after them */
static void test_includes(void)
{
	char text[PATH_MAX + 64], from[PATH_MAX], to[PATH_MAX], expected[4096];
	const char *bad[] = { "include =b.cfg", "include= b.cfg", "include = b.cfg", "include_dir =d", "include_dir=\td", "include= *.cfg" };
	const char *bad_limits[] = { "0", "-1", "abc", "12x", "", "99999999999" };
	const char *long_dirs[] = { "customers-of-the-north-region", "customers-of-the-north-region-and-island" };
	const char *plain = "$VAULT:P$=this is a plaintext file and must not be accepted\n";

	/* include directives */
	write_vault("n/vault.cfg", "$VAULT:R$=r\ninclude=a.cfg\n");
	write_vault("n/a.cfg", "include=b.cfg\n$VAULT:A$=a\n");
	write_vault("n/b.cfg", "$VAULT:B$=b\n");
	check("Nested includes", "n/vault.cfg", "", "OK: VAULT:R=r VAULT:B=b VAULT:A=a");
	write_file("n/plain.cfg", plain, strlen(plain));
	write_vault("n/p.cfg", "include=plain.cfg\n");
	check("Plaintext include", "n/p.cfg", "", "ERROR: n/plain.cfg is not a vim crypted file");
	for(size_t i = 0; i < ARRAY_SIZE(bad); i++) {
		snprintf(text, sizeof(text), "%s\n", bad[i]);
		write_vault("n/blank.cfg", text);
		snprintf(expected, sizeof(expected), "Blank around the equals sign: %s", bad[i]);
		check(expected, "n/blank.cfg", "", "ERROR: parse error in vault file");
	}
	write_vault("n/stripped.cfg", " \t include=b.cfg \t\n  # indented comment\n");
	check("leading and trailing blanks of a line are ignored", "n/stripped.cfg", "", "OK: VAULT:B=b");

	/* path resolution, the working directory is / */
	write_vault("etc/vault.cfg", "include=vault.d/site.cfg\n");
	write_vault("etc/vault.d/site.cfg", "$VAULT:S$=site\n");
	check("Relative to the including file", "etc/vault.cfg", "", "OK: VAULT:S=site");
	if(chdir(workdir) == 0) {
		check("relative vault argument", "unused", "vault=etc/vault.cfg", "OK: VAULT:S=site");
		if(chdir("/") != 0)
			exit(1);
	}
	write_vault("d/vault.cfg", "include_dir=level1\n");
	write_vault("d/level1/file1.cfg", "$VAULT:V$=before\ninclude_dir=level2\n$VAULT:L1$=after\n");
	write_vault("d/level1/level2/file21.cfg", "$VAULT:V$=21\n");
	write_vault("d/level1/level2/file22.cfg", "$VAULT:V$=22\n$VAULT:X$=x\n");
	write_vault("d/level2/decoy.cfg", "$VAULT:DECOY$=wrong\n");
	check("Nested directory directive", "d/vault.cfg", "", "OK: VAULT:V=22 VAULT:X=x VAULT:L1=after");
	write_vault("shared/real.cfg", "include=local.cfg\n");
	write_vault("shared/local.cfg", "$VAULT:L$=wrong\n");
	write_vault("site/local.cfg", "$VAULT:L$=site\n");
	snprintf(from, sizeof(from), "%s/shared/real.cfg", workdir);
	snprintf(to, sizeof(to), "%s/site/vault.cfg", workdir);
	ok(symlink(from, to) == 0, "create symlink site/vault.cfg");
	check("symlinked vault resolves includes from the link location", "site/vault.cfg", "", "OK: VAULT:L=site");
	snprintf(text, sizeof(text), "include=%s/n/b.cfg\n", workdir);
	write_vault("abs.cfg", text);
	check("absolute include path", "abs.cfg", "", "OK: VAULT:B=b");
	write_vault("site[1]{a}/vault.cfg", "include=b.cfg\n");
	write_vault("site[1]{a}/b.cfg", "$VAULT:B$=b\n");
	write_vault("site1a/b.cfg", "$VAULT:B$=decoy\n");
	check("Wildcard characters in the including directory", "site[1]{a}/vault.cfg", "", "OK: VAULT:B=b");
	write_vault("site[1]{a}/req.cfg", "include=missing.cfg\n");
	check("Required file next to a wildcard-named directory", "site[1]{a}/req.cfg", "", "ERROR: no such file");

	/* selection and order */
	write_vault("o/vault.cfg", "include=vault.d/db-*.cfg\n");
	write_vault("o/vault.d/db-b.cfg", "$VAULT:DB$=b\n$VAULT:B$=1\n");
	write_vault("o/vault.d/db-a.cfg", "$VAULT:DB$=a\n$VAULT:A$=1\n");
	check("Sorted matches", "o/vault.cfg", "", "OK: VAULT:DB=b VAULT:A=1 VAULT:B=1");
	write_vault("o/brace.cfg", "include=vault.d/db-{b,a}.cfg\n");
	check("brace alternatives in written order", "o/brace.cfg", "", "OK: VAULT:DB=a VAULT:B=1 VAULT:A=1");
	write_vault("s/vault.cfg", "include_dir=vault.d\n");
	write_vault("s/vault.d/a.cfg", "$VAULT:A$=a\n");
	write_vault("s/vault.d/sub/b.cfg", "$VAULT:B$=b\n");
	write_vault("s/vault.d/.hidden.cfg", "$VAULT:H$=h\n");
	write_file("s/vault.d/notes.txt", "junk\n", 5);
	check("No automatic descent, hidden and other files ignored", "s/vault.cfg", "", "OK: VAULT:A=a");
	write_vault("w/vault.cfg", "include_dir=*\n");
	write_vault("w/a/one.cfg", "$VAULT:A$=one\n");
	write_vault("w/b/two.cfg", "$VAULT:B$=two\n");
	write_vault("w/b/deeper/three.cfg", "$VAULT:D$=x\n");
	check("include_dir=* selects only immediate directories", "w/vault.cfg", "", "OK: VAULT:A=one VAULT:B=two");
	for(size_t i = 0; i < ARRAY_SIZE(long_dirs); i++) {
		snprintf(text, sizeof(text), "include_dir=%s\n", long_dirs[i]);
		write_vault("long/vault.cfg", text);
		snprintf(to, sizeof(to), "long/%s/a.cfg", long_dirs[i]);
		write_vault(to, "$VAULT:A$=a\n");
		snprintf(to, sizeof(to), "long/%s/notes.txt", long_dirs[i]);
		write_file(to, "junk\n", 5);
		snprintf(expected, sizeof(expected), "Long directory name: %zu characters", strlen(long_dirs[i]));
		check(expected, "long/vault.cfg", "", "OK: VAULT:A=a");
	}

	/* optional and required selections */
	write_vault("q/vault.cfg", "$VAULT:DEF$=default\ninclude=hosts/myhost-*.cfg\n");
	write_vault("q/hosts/other.cfg", "$VAULT:O$=other\n");
	check("Optional host file", "q/vault.cfg", "", "OK: VAULT:DEF=default");
	ok(strstr(logged, "Warning") == NULL, "Optional host file: no warning by default");
	check("Requested warning", "q/vault.cfg", "warn_no_match=yes", "OK: VAULT:DEF=default");
	ok(strstr(logged, "matches no files") != NULL, "Requested warning: warning logged");
	check("warn_no_match=no", "q/vault.cfg", "warn_no_match=no", "OK: VAULT:DEF=default");
	write_vault("q/onlyinc.cfg", "include=hosts/myhost-*.cfg\n");
	check("include-only vault, nothing matched", "q/onlyinc.cfg", "", "OK:");
	write_vault("q/emptydir.cfg", "include_dir=empty\n");
	snprintf(from, sizeof(from), "%s/q/empty", workdir);
	nspath_mkdir_p(from, 0700, 0);
	check("include_dir of an empty directory", "q/emptydir.cfg", "", "OK:");
	write_vault("q/req.cfg", "include=required.cfg\n");
	check("Missing required file", "q/req.cfg", "", "ERROR: no such file");
	write_vault("q/reqdir.cfg", "include_dir=missing\n");
	check("missing include_dir", "q/reqdir.cfg", "", "ERROR: include_dir=missing in vault file");
	write_vault("q/wilddir.cfg", "include=missing/*.cfg\n");
	snprintf(expected, sizeof(expected), "ERROR: include=missing/*.cfg in vault file %s/q/wilddir.cfg", workdir);
	check("Wildcard in a missing directory", "q/wilddir.cfg", "", expected);
	check("Invalid warn_no_match: 1", "q/vault.cfg", "warn_no_match=1", "ERROR: warn_no_match must be yes or no");
	check("Invalid warn_no_match: no value", "q/vault.cfg", "warn_no_match", "ERROR: warn_no_match must be yes or no");
	check("unknown module argument", "q/vault.cfg", "foo=bar", "ERROR: unknown module argument");

	/* duplicates and file limit */
	write_vault("c/vault.cfg", "include=a.cfg\n");
	write_vault("c/a.cfg", "include=vault.cfg\n");
	check("Cycle", "c/vault.cfg", "", "ERROR: c/vault.cfg is included more than once");
	write_vault("c/b.cfg", "$VAULT:B$=b\n");
	snprintf(from, sizeof(from), "%s/c/b.cfg", workdir);
	snprintf(to, sizeof(to), "%s/c/alias.cfg", workdir);
	ok(symlink(from, to) == 0, "create symlink c/alias.cfg");
	write_vault("c/dup.cfg", "include=b.cfg\ninclude=b.cfg\n");
	check("duplicate: repeated include", "c/dup.cfg", "", "ERROR: included more than once");
	write_vault("c/dup.cfg", "include=b*.cfg\ninclude=?.cfg\n");
	check("duplicate: overlapping patterns", "c/dup.cfg", "", "ERROR: included more than once");
	write_vault("c/dup.cfg", "include=b.cfg\ninclude=alias.cfg\n");
	check("duplicate: symlink alias", "c/dup.cfg", "", "ERROR: included more than once");
	write_vault("c/dup.cfg", "include=b.cfg\ninclude=../c/b.cfg\n");
	check("duplicate: path with ..", "c/dup.cfg", "", "ERROR: included more than once");

	for(int i = 0; i < 64; i++) {
		snprintf(text, sizeof(text), "$VAULT:%d$=%d\n", i, i);
		snprintf(to, sizeof(to), "lim/f/%02d.cfg", i);
		write_vault(to, text);
	}
	strcpy(expected, "OK:");
	for(int i = 0; i < 63; i++)
		snprintf(expected + strlen(expected), sizeof(expected) - strlen(expected), " VAULT:%d=%d", i, i);
	write_vault("lim/63.cfg", "include=f/[0-5]?.cfg\ninclude=f/6[0-2].cfg\n");
	check("Limit: 64 files including the vault", "lim/63.cfg", "", expected);
	write_file("lim/f/63.cfg", plain, strlen(plain));
	write_vault("lim/64.cfg", "include=f/[0-5]?.cfg\ninclude=f/6[0-3].cfg\n");
	check("Limit: the 65th file is rejected before it is read", "lim/64.cfg", "", "ERROR: max_files=64 reached");
	check("max_files=128", "lim/63.cfg", "max_files=128", expected);
	check("max_files=1 allows the vault alone", "n/b.cfg", "max_files=1", "OK: VAULT:B=b");
	check("max_files=1 rejects an include", "n/a.cfg", "max_files=1", "ERROR: max_files=1 reached");
	for(size_t i = 0; i < ARRAY_SIZE(bad_limits); i++) {
		snprintf(text, sizeof(text), "max_files=%s", bad_limits[i]);
		snprintf(expected, sizeof(expected), "Invalid limit: %s", text);
		check(expected, "n/b.cfg", text, "ERROR: max_files must be a positive number");
	}
	for(int i = 0; i < 40; i++) {
		snprintf(text, sizeof(text), i < 39 ? "include=%d.cfg\n" : "$VAULT:END$=end\n", i + 1);
		snprintf(to, sizeof(to), "chain/%d.cfg", i);
		write_vault(to, text);
	}
	check("chain of 40 files, no depth limit", "chain/0.cfg", "", "OK: VAULT:END=end");

	/* last definition wins */
	write_vault("p/vault.cfg", "$VAULT:DB$=default\n$VAULT:DB$=again\ninclude=over.cfg\n$VAULT:DB$=trailing\n");
	write_vault("p/over.cfg", "$VAULT:DB$=included\n");
	check("Override and trailing override", "p/vault.cfg", "", "OK: VAULT:DB=trailing");
	write_vault("p/default.cfg", "$VAULT:DB$=default\ninclude=over.cfg\n");
	check("include overrides a default", "p/default.cfg", "", "OK: VAULT:DB=included");

	/* non-empty vault files */
	write_vault("e/vault.cfg", "$VAULT:A$=a\ninclude=comment.cfg\n");
	write_vault("e/comment.cfg", "# placeholder\n");
	check("Comment-only file", "e/vault.cfg", "", "OK: VAULT:A=a");
	write_vault("e/comment-root.cfg", "# only a comment\n");
	check("comment-only vault", "e/comment-root.cfg", "", "OK:");
	write_vault("e/inc.cfg", "$VAULT:A$=a\ninclude=x.cfg\n");
	write_vault("e/x.cfg", "");
	check("Empty or whitespace-only file: empty include", "e/inc.cfg", "", "ERROR: e/x.cfg, wrong password?");
	write_vault("e/x.cfg", "  \n\t\n\n");
	check("Empty or whitespace-only file: whitespace-only include", "e/inc.cfg", "", "ERROR: e/x.cfg, wrong password?");

	/* atomic load */
	write_vault("f/vault.cfg", "$VAULT:A$=a\ninclude=x/y.cfg\n");
	write_vault("f/x/y.cfg", "$VAULT:Y$=y\ninclude=z.cfg\n");
	write_vault("f/x/z.cfg", "garbage line\n");
	check("Failing nested include", "f/vault.cfg", "", "ERROR: parse error in vault file");
	ok(!partial_store, "Failing nested include: no partial macro store is kept");
}

static void test_master_password(void)
{
	char password[] = "forty characters of master password, ok!", args[PATH_MAX + 16];
	int loaded;

	fixture_password = password;
	write_vault("pw/vault.cfg", "$VAULT:PW$=opened\n");
	fixture_password = "test";

	/* entered at startup, then naemon formats short strings for every check job */
	remember_password(password);
	for(int i = 0; i < 300; i++)
		mkstr("%d", i);

	/* a reload without password argument or environment */
	master_password = NULL;
	unsetenv("NAEMON_VIM_MASTER_PASSWORD");
	snprintf(args, sizeof(args), "vault=%s/pw/vault.cfg", workdir);
	loaded = nebmodule_init(0, args, NULL) == OK;
	ok(loaded && !strcmp(kvvec_fetch_str_str(macro_store, "VAULT:PW"), "opened"), "Long password survives a reload");
	kvvec_destroy(macro_store, KVVEC_FREE_ALL);
	macro_store = NULL;
}

static int remove_entry(const char *path, const struct stat *st, int flag, struct FTW *ftw)
{
	return remove(path);
}

int main(void)
{
	const char *srcdir = getenv("srcdir");
	char kat_rel[PATH_MAX], *kat_dir;

	setvbuf(stdout, NULL, _IOLBF, 0);
	if(!mkdtemp(workdir)) {
		printf("Bail out! cannot create %s\n", workdir);
		return 1;
	}
	snprintf(kat_rel, sizeof(kat_rel), "%s/tests/vim", srcdir ? srcdir : ".");
	kat_dir = nspath_absolute(kat_rel, NULL);
	snprintf(logpath, sizeof(logpath), "%s/naemon.log", workdir);
	log_file = logpath;
	logging_options = ~0UL;
	use_syslog = FALSE;
	daemon_mode = TRUE;

	/* relative paths must never depend on the working directory */
	if(chdir("/") != 0)
		return 1;

	test_vim_compatibility(kat_dir);
	test_single_file();
	test_bounds();
	test_includes();
	test_master_password();

	close_log_file();
	nftw(workdir, remove_entry, 16, FTW_DEPTH | FTW_PHYS);
	free(kat_dir);
	printf("1..%d\n", tests);
	return failures ? 1 : 0;
}
